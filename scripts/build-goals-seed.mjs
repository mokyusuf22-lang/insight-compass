#!/usr/bin/env node
// Builds the goal catalogue seed from supabase/seed/goals/*.json.
//
//   node scripts/build-goals-seed.mjs
//
// Writes:
//   supabase/migrations/20260930130100_seed_goals.sql   (upserts every goal)
//   src/data/goalFallback.ts                            (popular goals, used offline)
//
// Each JSON file is [{ category, goals: ["Label | keyword, keyword", ...] }].
// Popularity: POPULAR labels get 100, the first 3 goals of each category get 40.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const SEED_DIR = join(ROOT, 'supabase/seed/goals');
const SQL_OUT = join(ROOT, 'supabase/migrations/20260930130100_seed_goals.sql');
const TS_OUT = join(ROOT, 'src/data/goalFallback.ts');

const POPULAR = [
  'Climb Kilimanjaro', 'Run a marathon', 'Pass my driving test', 'Pass an exam', 'Get promoted',
  'Start a side business', 'Get fit and strong', 'Build a calmer routine', 'Write a book',
  'Learn conversational Spanish', 'Save for a home deposit', 'Speak confidently in public',
];

const slugify = (s) => s.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '')
  .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 80);
const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;

const goals = new Map();
const dupes = [];
for (const file of readdirSync(SEED_DIR).filter((f) => f.endsWith('.json')).sort()) {
  const groups = JSON.parse(readFileSync(join(SEED_DIR, file), 'utf8'));
  for (const { category, goals: items } of groups) {
    items.forEach((entry, i) => {
      const [labelRaw, keywordsRaw = ''] = entry.split('|');
      const label = labelRaw.trim();
      const id = slugify(label);
      if (!label || !id) throw new Error(`Bad entry in ${file}: ${entry}`);
      if (goals.has(id)) { dupes.push(`${label} (${category} vs ${goals.get(id).category})`); return; }
      const keywords = keywordsRaw.split(',').map((k) => k.trim().toLowerCase()).filter(Boolean).join(', ');
      const popularity = POPULAR.includes(label) ? 100 : i < 3 ? 40 : 0;
      goals.set(id, { id, label, category, keywords, popularity });
    });
  }
}

const missingPopular = POPULAR.filter((l) => !goals.has(slugify(l)));
if (missingPopular.length) throw new Error(`Popular goals missing from catalogue: ${missingPopular.join(', ')}`);

const rows = [...goals.values()];
const values = rows.map((g) => `  (${sql(g.id)}, ${sql(g.label)}, ${sql(g.category)}, ${sql(g.keywords)}, ${g.popularity})`);
writeFileSync(SQL_OUT, `-- Generated by scripts/build-goals-seed.mjs from supabase/seed/goals/*.json. Do not edit by hand.
-- ${rows.length} goals across ${new Set(rows.map((g) => g.category)).size} categories.
INSERT INTO public.goals (id, label, category, keywords, popularity) VALUES
${values.join(',\n')}
ON CONFLICT (id) DO UPDATE SET
  label = EXCLUDED.label,
  category = EXCLUDED.category,
  keywords = EXCLUDED.keywords,
  popularity = EXCLUDED.popularity;
`);

const fallback = rows.filter((g) => g.popularity > 0).sort((a, b) => b.popularity - a.popularity);
writeFileSync(TS_OUT, `// Generated by scripts/build-goals-seed.mjs. Do not edit by hand.
// Popular goals used when the goals search RPC is unavailable (offline, or before migration).
export interface CatalogueGoal { id: string; label: string; category: string; keywords: string }

export const GOAL_FALLBACK: CatalogueGoal[] = ${JSON.stringify(
  fallback.map(({ id, label, category, keywords }) => ({ id, label, category, keywords })), null, 2)};
`);

console.log(`${rows.length} goals, ${new Set(rows.map((g) => g.category)).size} categories, ${fallback.length} in fallback.`);
if (dupes.length) console.log(`Skipped ${dupes.length} duplicate labels:\n  ${dupes.join('\n  ')}`);
